import {test,expect} from '@playwright/test';
test('create funding and budget, spend, report, reconcile and void',async({page,context})=>{
 await page.goto('/');
 await page.getByLabel('Username').fill(process.env.STAFF_USER!);
 await page.getByLabel('Password',{exact:true}).fill(process.env.STAFF_PASSWORD!);
 await page.getByRole('button',{name:'Sign in'}).click();
 await page.getByRole('button',{name:'Funding & grants',exact:true}).click();
 const grant=page.locator('section').filter({has:page.getByRole('heading',{name:'Add funding',exact:true})});
 await grant.getByLabel('Funding source',{exact:true}).fill('Browser fictional grant');
 await grant.getByLabel('Total award (CAD)').fill('1000');
 await grant.getByLabel('Confirmed received (CAD)').fill('1000');
 await grant.getByRole('button',{name:'Save funding'}).click();
 await expect(page.getByText('Record saved successfully.')).toBeVisible();
 await page.getByRole('button',{name:'Programs & budgets',exact:true}).click();
 const budget=page.locator('section').filter({has:page.getByRole('heading',{name:'Allocate funding to a program',exact:true})});
 const grantOption=budget.getByLabel('Funding source').locator('option').filter({hasText:'Browser fictional grant'});
 await budget.getByLabel('Funding source').selectOption(await grantOption.getAttribute('value')||'');
 await budget.getByLabel('Program',{exact:true}).selectOption('ASUFCGR');
 await budget.getByLabel('Budget amount (CAD)').fill('600');
 await budget.getByRole('button',{name:'Create budget allocation'}).click();
 await expect(page.getByText('Record saved successfully.')).toBeVisible();
 await page.getByRole('button',{name:'Transactions',exact:true}).click();
 await page.getByLabel('Purchase date').fill('2026-11-01');
 await page.getByLabel('Supplier',{exact:true}).fill('Browser fictional shop');
 await page.getByLabel('Purchase type',{exact:true}).fill('Groceries');
 await page.getByLabel('Purchase total (CAD)').fill('250');
 const option=page.getByLabel('Program / funding').locator('option').filter({hasText:'Browser fictional grant'});
 await page.getByLabel('Program / funding').selectOption(await option.getAttribute('value')||'');
 await page.getByLabel('Amount (CAD)',{exact:true}).fill('250');
 await page.getByRole('button',{name:'Confirm and save purchase'}).click();
 await expect(page.getByText('Record saved successfully.')).toBeVisible();
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await expect(page.locator('.metric').filter({hasText:'Cash remaining'})).toContainText('750.00');
 await page.getByRole('button',{name:'Reports',exact:true}).click();
 await expect(page.locator('.metric').filter({hasText:'Cash spent'})).toContainText('250.00');
 const downloaded=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download Excel report'}).click();
 expect((await downloaded).suggestedFilename()).toBe('asufc-spending.xlsx');
 await page.getByRole('button',{name:'Reconciliation',exact:true}).click();
 await expect(page.getByText('No internal inconsistencies detected')).toBeVisible();
 await page.getByRole('button',{name:'History',exact:true}).click();
 const purchase=page.getByLabel('Purchase to void').locator('option').filter({hasText:'Browser fictional shop'});
 await page.getByLabel('Purchase to void').selectOption(await purchase.getAttribute('value')||'');
 await page.getByLabel('Reason for voiding').fill('Browser regression');
 page.once('dialog',d=>d.accept());
 await page.getByRole('button',{name:'Confirm void'}).click();
 await expect(page.getByRole('row').filter({hasText:'Browser fictional shop'})).toContainText('voided');
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await expect(page.locator('.metric').filter({hasText:'Cash remaining'})).toContainText('1,000.00');
});
